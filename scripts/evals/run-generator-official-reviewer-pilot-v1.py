#!/usr/bin/env python3
"""Official generator + e2e-reviewer pass ("B") on the saved official-generator deliverables: descriptive pilot. Apache-2.0.

Arm B takes each of the 12 saved `official-generator` deliverables of generator-official-pilot-v1, stages a fresh fixture
project exactly like that pilot (same v3 engine.stage, specs/plan.md, tests/seed.spec.ts, image, model, effort, timeout),
copies the official specs into it and makes ONE Codex call that reviews and fixes them with the 2.0.1 `e2e-reviewer`.
Scoring is the unchanged v3 engine / v8 scanner, so B is directly comparable with the saved arms A (official) and C (ours).
It reuses run-generator-official-pilot-v1.py by import and edits none of its files. No model call happens without
`run --allow-live`; there is no PASS/FAIL verdict.
"""
import argparse
import importlib.util
import json
import os
import random
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts/evals"))
spec = importlib.util.spec_from_file_location("gop1", ROOT / "scripts/evals/run-generator-official-pilot-v1.py")
orig = importlib.util.module_from_spec(spec)
spec.loader.exec_module(orig)
engine = orig.engine

BENCH = ROOT / "benchmarks/generator-official-reviewer-pilot-v1"
PROTOCOL = BENCH / "protocol.json"
LOCK = BENCH / "freeze.json"
ARM = "official+reviewer"
ARM_A, ARM_C = "official-generator", "ours-2.0.1"
ARMS3 = (ARM_A, ARM, ARM_C)
SOURCE_DIR = Path(os.environ.get("OFFGEN_PILOT_V1_DIR") or Path.home() / ".cache/e2e-skills-bench/offgen-pilot-v1")
REVIEWER_STAGED = "/work/skill/e2e-reviewer"  # container path of the staged reviewer; work/ is mounted at /work

TASK_LINE = """

The user has approved the scenario plan frozen at `specs/plan.md` (seed test: `tests/seed.spec.ts`). Playwright spec files that implement that plan were already generated by another tool and sit untracked in `tests/`. Do not generate tests from scratch: your job is the review-and-fix pass over those generated files, described below."""
REVIEW_LINE = f"""

Review the generated spec files with the `e2e-reviewer` skill. Its SKILL.md is at {REVIEWER_STAGED}/SKILL.md; read it and follow its workflow from Phase 0 through its report, including the reference files it names (the `Skill` tool is not available here, so apply the skill by reading that file). Review scope: the untracked files under `tests/` (`git status --porcelain --untracked-files=all tests/`); `tests/seed.spec.ts` and the pre-existing spec are context only. One additional per-row approval: the bundled scanner `/bin/bash -p {REVIEWER_STAGED}/scripts/scan.sh`, run exactly as the skill's `references/scanner-workflow.md` Phase 1 pins it.

Then FIX every finding in place in those files: every P0 finding, and every P1 and P2 finding whose fix is mechanical. Fix a finding only after the skill's Phase 2 rules confirm it; leave a scanner hit that the skill classifies as a false positive alone, and use a `// JUSTIFIED:` comment only where the skill allows it. Constraints: keep every scenario of the approved plan covered; do not weaken assertions (do not delete, loosen or replace them with weaker checks, and do not add `test.skip`, `test.fixme`, empty `catch`, fixed sleeps or `expect(true)`); add no scenarios; do not touch `app.mjs`, `playwright.config.mjs`, `package.json` or any file outside `tests/`. After fixing, rerun the scanner, then run `node_modules/.bin/playwright test <the files>` and, if a fix broke a test, repair it within the same constraints. In the summary list the findings by severity as found, fixed and left unfixed (with the reason); `spec_files` lists every generated spec file you reviewed, changed or not."""


def digest(path):
    return orig.digest(path)


def read(path):
    return orig.read(path)


def protocol():
    p = read(PROTOCOL)
    if p["protocol_id"] != "generator-official-reviewer-pilot-v1" or p["arms"] != [ARM] or p["compared_arms"] != list(ARMS3):
        raise ValueError("unexpected protocol or arms")
    if p["repetitions"] != 2 or p["workers"] != 1 or len(p["tasks"]) != 6:
        raise ValueError("schedule contract changed")
    base = orig.protocol()
    for key in ("tasks", "model", "reasoning_effort", "timeout_s", "container_image", "docker_context", "load",
                "minimum_free_disk_bytes"):
        if p[key] != base[key]:
            raise ValueError(f"{key} differs from generator-official-pilot-v1")
    return p


def schedule(p=None):
    p = p or protocol()
    rows = [{"case": c, "arm": ARM, "repetition": r} for r in range(1, p["repetitions"] + 1) for c in p["tasks"]]
    random.Random(p["seed"]).shuffle(rows)
    return [dict(row, ordinal=i) for i, row in enumerate(rows, 1)]


def identity(row):
    return row["case"], row["arm"], row["repetition"]


def source_call_id(item):
    return f"{item['case']}-{ARM_A}-r{item['repetition']}"


def source_artifacts(item):
    return SOURCE_DIR / "final-artifacts" / source_call_id(item)


def source_evidence():
    """Digests of the saved official-pilot outputs that arms A and C and the B inputs come from."""
    out = {"final_json": digest(SOURCE_DIR / "final.json"), "scores_json": digest(SOURCE_DIR / "scores.json"), "artifacts": {}}
    for item in schedule():
        art = source_artifacts(item)
        if not (art / "tests").is_dir():
            raise ValueError("saved official deliverable missing: " + source_call_id(item))
        out["artifacts"][source_call_id(item)] = orig.tree(art)
    return out


def bindings():
    o = orig.engine
    return {"protocol": digest(PROTOCOL), "runner": digest(Path(__file__)),
            "original_runner": digest(ROOT / "scripts/evals/run-generator-official-pilot-v1.py"),
            "original_protocol": digest(orig.PROTOCOL), "original_freeze": digest(orig.LOCK),
            "adapter": digest(ROOT / "scripts/evals/generator_codex_official_adapter.py"),
            "auth_helper": digest(ROOT / "scripts/evals/run-reviewer-holdout.py"),
            "shared_adapter": digest(ROOT / "scripts/evals/generator_codex_adapter_v2.py"),
            "dockerfile": digest(ROOT / "scripts/evals/generator-codex-container/Dockerfile"),
            "fixture_package": digest(ROOT / "scripts/evals/fixtures/package.json"),
            "fixture_lock": digest(ROOT / "scripts/evals/fixtures/package-lock.json"),
            "engine_inputs": o.input_digests(),
            "plans": {c: digest(orig.PLANS / c / "plan.md") for c in orig.select_tasks()},
            "seed": orig.sha(orig.SEED),
            "prompt_lines": {"frame": orig.sha(o.FRAME), "task": orig.sha(TASK_LINE), "review": orig.sha(REVIEW_LINE)},
            "reviewer_skill_tree": orig.sha(json.dumps(orig.tree(orig.OURS_SKILLS / "e2e-reviewer"), sort_keys=True)),
            "source_evidence": source_evidence()}


def frozen():
    lock = read(LOCK)
    orig.frozen()  # the original pilot's own freeze must still match its files
    if lock["bindings"] != bindings() or lock["schedule"] != schedule():
        raise ValueError("frozen protocol, runner, inputs, saved evidence or schedule drift")
    return lock


def check_report(report, lock, complete=True):
    p = protocol()
    if report["protocol_id"] != p["protocol_id"] or report["freeze_sha256"] != digest(LOCK):
        raise ValueError("report is not bound to this freeze")
    if report["arms"] != [ARM] or report["model"] != p["model"] or report.get("workers") != 1:
        raise ValueError("unexpected report arms, model or workers")
    if report["completed_calls"] != len(report["runs"]) or report.get("input_drift"):
        raise ValueError("reported call count mismatch or drift")
    if report.get("container_image") != p["container_image"]:
        raise ValueError("container identity differs from protocol")
    orig.check_rows(report["runs"], lock["schedule"], complete)


def prepare_workspace(project, case, item):
    """Same plan/seed/baseline commit as the ours arm; the official specs are then copied in as untracked files."""
    setup = orig.prepare_workspace(project, case, ARM_C)  # non-official branch: plan + seed + git baseline only
    shutil.copytree(source_artifacts(item) / "tests", project / "tests", dirs_exist_ok=True)
    return setup


def stage_reviewer(work):
    shutil.copytree(orig.OURS_SKILLS / "e2e-reviewer", work / "skill/e2e-reviewer",
                    ignore=shutil.ignore_patterns("evals", "__pycache__"))


def one_call(item, args, ports, artifacts):
    case, rep = item["case"], item["repetition"]
    task = engine.load_truth(case)["task"] + TASK_LINE
    record = dict(item, attempts=[], source_call_id=source_call_id(item))
    call_id = f"{case}-{ARM}-r{rep}"
    engine.wait_for_load(record)
    for attempt in (1, 2):
        work = Path(tempfile.mkdtemp(prefix=f"gorp1-{item['ordinal']}-")).resolve()
        project = engine.stage(engine.CASES / case, ports.take(), work, git=False)
        record["setup"] = prepare_workspace(project, case, item)
        stage_reviewer(work)
        result = engine.call_model(project, work, ARM, task, args.model, args.timeout, args.call_budget)
        result["attempt"] = attempt
        record["attempts"].append(result)
        if result["infrastructure_error"]:
            shutil.rmtree(work, ignore_errors=True)
            continue
        record.update(engine.collect_deliverable(project, artifacts / call_id), call_id=call_id,
                      cost_usd=None, elapsed_ms=result["elapsed_ms"], timeout=result["timeout"],
                      num_turns=result.get("num_turns"), usage=result.get("usage"),
                      usage_all_turns=result.get("usage_all_turns"), transcript_path=result.get("transcript_path"),
                      structured_output=result.get("structured_output"), result_text=result.get("result_text"),
                      compliance=result.get("compliance"))
        shutil.rmtree(work, ignore_errors=True)
        break
    record["infrastructure_error"] = "spec_files" not in record
    record["deliverable"] = bool(record.get("spec_files"))
    return record


def run(args):
    if not args.allow_live:
        raise ValueError("run requires --allow-live; this command incurs model usage")
    lock, p = frozen(), protocol()
    orig.output_guard(args.output)
    if args.output.exists() and not args.resume:
        raise ValueError("output exists; use --resume")
    work_root, image_id, cli = orig.configure_live(args, p)
    import generator_codex_official_adapter as adapter
    adapter.ARM_LINES[ARM] = REVIEW_LINE
    rows = []
    if args.resume and args.output.exists():
        prior = read(args.output)
        check_report(prior, lock, complete=False)
        if prior["cli"] != cli or prior.get("container_image") != image_id:
            raise ValueError("CLI or image changed during resume")
        rows = prior["runs"]
    done = {identity(row) for row in rows}
    ports = engine.Ports(6300)
    artifacts = args.output.parent / (args.output.stem + "-artifacts")
    engine.CODEX_TRANSCRIPTS = args.output.parent / (args.output.stem + "-transcripts")
    total = len(lock["schedule"])

    def flush():
        engine.write_json(args.output, {
            "protocol_id": p["protocol_id"], "freeze_sha256": digest(LOCK), "stage": "final", "arms": [ARM],
            "model": p["model"], "cli": cli, "container_image": image_id, "docker_context": p["docker_context"],
            "scheduled_calls": total, "completed_calls": len(rows), "workers": 1, "input_drift": False, "stopped": None,
            "spent_usd": None, "cost_note": "Codex CLI provides token usage, not billed USD", "runs": rows})
    flush()
    for item in lock["schedule"]:
        if identity(item) in done:
            continue
        frozen()
        if shutil.disk_usage(work_root).free < p["minimum_free_disk_bytes"]:
            raise ValueError("disk safety floor reached; partial report preserved")
        rows.append(one_call(item, args, ports, artifacts))
        flush()
        print(f"completed {len(rows)}/{total} {rows[-1].get('call_id')} deliverable={rows[-1]['deliverable']} "
              f"ms={rows[-1].get('elapsed_ms')}", flush=True)
        if rows[-1]["infrastructure_error"]:
            raise ValueError("infrastructure failure; stop and preserve partial report")
    return 0


def score(args):
    lock = frozen()
    report = read(args.report)
    check_report(report, lock)
    orig.output_guard(args.output)
    before = digest(args.report)
    if args.output.exists() and (not args.resume or read(args.output).get("report_sha256") != before):
        raise ValueError("score output exists or resume report binding changed")
    original_write = engine.write_json

    def bound_write(path, data):
        data.update(report_sha256=before, freeze_sha256=digest(LOCK))
        original_write(path, data)
    engine.write_json = bound_write
    try:
        engine.cmd_score(args)
    finally:
        engine.write_json = original_write
    if digest(args.report) != before:
        raise ValueError("report changed during scoring")
    return 0


def mean(values):
    vals = [v for v in values if v is not None]
    return round(sum(vals) / len(vals), 4) if vals else None


def make_cell(row, rec, report_path):
    scan = row.get("scan") or {}
    return {"call_id": row["call_id"], "case": row["case"], "arm": row["arm"], "repetition": row["repetition"],
            "deliverable": row["deliverable"], "clean": row["clean"], "refactor_score": row["refactor_score"],
            "effective_fault_kill": row["primary"], "kill_rate": row["kill_rate"],
            "faults_escaped": sorted(f for f, r in (row.get("faults") or {}).items() if not r["killed"]),
            "scan_p0": scan.get("p0"), "scan_p1p2": scan.get("p1p2"), "scan_pattern_ids": scan.get("pattern_ids"),
            "weak_text_probe_hits": orig.weakening_probe(report_path, rec),
            "elapsed_s": round((rec.get("elapsed_ms") or 0) / 1000, 1), "usage": orig.usage_sums(rec),
            "timeout": row["timeout"], "self_reported_status": row.get("self_reported_status"),
            "spec_files": row["spec_files"], "out_of_scope_writes": row.get("out_of_scope_writes"),
            "flaky_clean_runs": bool(row["clean_runs"] and not row["clean"] and any(r["ok"] for r in row["clean_runs"]))}


def changed_files(b_cell, report_path):
    """How many of the official spec files the reviewer pass actually modified, removed or added (sha comparison)."""
    src = source_artifacts(b_cell)
    mine = report_path.parent / (report_path.stem + "-artifacts") / b_cell["call_id"]
    before = orig.tree(src) if src.is_dir() else {}
    after = orig.tree(mine) if mine.is_dir() else {}
    return {"modified": sorted(k for k in before if k in after and before[k] != after[k]),
            "removed": sorted(k for k in before if k not in after), "added": sorted(k for k in after if k not in before)}


def arm_summary(cells):
    s = lambda key: sum(c[key] or 0 for c in cells)
    tok = lambda kind: {k: sum(c["usage"][kind][k] for c in cells) for k in ("input_tokens", "cached_input_tokens", "output_tokens")}
    return {"cells": len(cells), "delivered": sum(c["deliverable"] for c in cells),
            "refactor_survival": mean(c["refactor_score"] for c in cells),
            "clean_all_three": mean(float(c["clean"]) for c in cells),
            "effective_fault_kill": mean(c["effective_fault_kill"] for c in cells), "kill_rate": mean(c["kill_rate"] for c in cells),
            "scan_p0_total": s("scan_p0"), "scan_p1p2_total": s("scan_p1p2"),
            "flaky_calls": sum(c["flaky_clean_runs"] for c in cells), "timeouts": sum(c["timeout"] for c in cells),
            "weak_text_probe_cells": sum(bool(c["weak_text_probe_hits"]) for c in cells),
            "call_s_sum": round(s("elapsed_s"), 1), "tokens_last_turn": tok("last_turn"), "tokens_sum_turns": tok("sum_turns")}


def task_entry(cells, case, arm):
    rows = [c for c in cells if c["case"] == case and c["arm"] == arm]
    return {"refactor_survival": mean(c["refactor_score"] for c in rows), "clean_cells": sum(c["clean"] for c in rows),
            "effective_fault_kill": mean(c["effective_fault_kill"] for c in rows),
            "scan_p0": sum(c["scan_p0"] or 0 for c in rows), "scan_p1p2": sum(c["scan_p1p2"] or 0 for c in rows)}


def suggestive(per_task, summary, x, y):
    """Protocol rule: same sign on refactor survival in >=5 of 6 tasks, with neither guard worse for the same arm."""
    diffs = [per_task[c][x]["refactor_survival"] - per_task[c][y]["refactor_survival"] for c in per_task]
    better, worse = sum(d > 0 for d in diffs), sum(d < 0 for d in diffs)
    out = {"x_better_tasks": better, "tied_tasks": sum(d == 0 for d in diffs), "x_worse_tasks": worse, "tasks": len(diffs)}
    for lead, count in ((x, better), (y, worse)):
        a, b = summary[lead], summary[y if lead == x else x]
        guards_ok = (a["clean_all_three"] >= b["clean_all_three"] and a["effective_fault_kill"] >= b["effective_fault_kill"]
                     and a["scan_p0_total"] <= b["scan_p0_total"] and a["scan_p1p2_total"] <= b["scan_p1p2_total"])
        out["guards_not_worse_" + ("x" if lead == x else "y")] = guards_ok
        if count >= protocol()["evidence_interpretation"]["min_tasks_same_sign"] and guards_ok:
            out["label"] = f"suggestive: {lead} better"
            return out
    out["label"] = "nothing (rule not met)"
    return out


def analyze(args):
    lock, p = frozen(), protocol()
    orig.output_guard(args.output)
    scored = read(args.scores)
    report_path = args.scores.parent / scored["report"]
    report = read(report_path)
    check_report(report, lock)
    if scored.get("report_sha256") != digest(report_path) or scored.get("freeze_sha256") != digest(LOCK):
        raise ValueError("scores are not bound to the exact report and freeze")
    orig.check_rows(scored["scores"], lock["schedule"])
    base_report_path = SOURCE_DIR / "final.json"
    base_scored = read(SOURCE_DIR / "scores.json")
    if base_scored["report_sha256"] != digest(base_report_path) or base_scored["freeze_sha256"] != digest(orig.LOCK):
        raise ValueError("saved A/C scores are not bound to the original pilot report and freeze")
    base_records = {identity(r): r for r in read(base_report_path)["runs"]}
    cells = []
    for row in base_scored["scores"]:
        cells.append(make_cell(row, base_records[identity(row)], base_report_path))
    records = {identity(r): r for r in report["runs"]}
    b_cells = []
    for row in scored["scores"]:
        cell = make_cell(row, records[identity(row)], report_path)
        a = next(c for c in cells if c["case"] == row["case"] and c["repetition"] == row["repetition"] and c["arm"] == ARM_A)
        cell["reviewer_changes"] = changed_files(row, report_path)
        cell["official_generation_s"] = a["elapsed_s"]
        cell["official_generation_plus_review_s"] = round(a["elapsed_s"] + cell["elapsed_s"], 1)
        b_cells.append(cell)
    cells += b_cells
    summary = {arm: arm_summary([c for c in cells if c["arm"] == arm]) for arm in ARMS3}
    a_cells = [c for c in cells if c["arm"] == ARM_A]
    summary[ARM]["reviewer_pass_s_sum"] = summary[ARM]["call_s_sum"]
    summary[ARM]["official_generation_s_sum_same_cells"] = summary[ARM_A]["call_s_sum"]
    summary[ARM]["official_generation_plus_reviewer"] = {
        "seconds": round(summary[ARM_A]["call_s_sum"] + summary[ARM]["call_s_sum"], 1),
        "tokens_last_turn": {k: summary[ARM_A]["tokens_last_turn"][k] + summary[ARM]["tokens_last_turn"][k]
                             for k in summary[ARM]["tokens_last_turn"]},
        "tokens_sum_turns": {k: summary[ARM_A]["tokens_sum_turns"][k] + summary[ARM]["tokens_sum_turns"][k]
                             for k in summary[ARM]["tokens_sum_turns"]}}
    summary[ARM]["cells_with_reviewer_edits"] = sum(bool(c["reviewer_changes"]["modified"] or c["reviewer_changes"]["removed"]
                                                       or c["reviewer_changes"]["added"]) for c in b_cells)
    per_task = {c: {arm: task_entry(cells, c, arm) for arm in ARMS3} for c in p["tasks"]}
    paired = {}
    for case, entry in per_task.items():
        paired[case] = {
            "B_minus_A_refactor": round(entry[ARM]["refactor_survival"] - entry[ARM_A]["refactor_survival"], 4),
            "B_minus_C_refactor": round(entry[ARM]["refactor_survival"] - entry[ARM_C]["refactor_survival"], 4),
            "B_minus_A_fault_kill": round(entry[ARM]["effective_fault_kill"] - entry[ARM_A]["effective_fault_kill"], 4),
            "B_minus_C_fault_kill": round(entry[ARM]["effective_fault_kill"] - entry[ARM_C]["effective_fault_kill"], 4),
            "B_minus_A_clean_cells": entry[ARM]["clean_cells"] - entry[ARM_A]["clean_cells"],
            "B_minus_C_clean_cells": entry[ARM]["clean_cells"] - entry[ARM_C]["clean_cells"]}
    engine.write_json(args.output, {
        "protocol_id": p["protocol_id"], "status": "DESCRIPTIVE_ONLY", "no_pass_fail_claim": True,
        "arm_labels": {"A": ARM_A, "B": ARM, "C": ARM_C}, "arm_summary": summary,
        "per_task": per_task, "per_task_paired": paired,
        "suggestive_evidence": {"B_vs_A": suggestive(per_task, summary, ARM, ARM_A), "B_vs_C": suggestive(per_task, summary, ARM, ARM_C),
                                "A_vs_C_original_pilot": suggestive(per_task, summary, ARM_A, ARM_C)},
        "cells": cells, "scores_sha256": digest(args.scores), "report_sha256": digest(report_path), "freeze_sha256": digest(LOCK),
        "saved_arms_a_c_from": str(SOURCE_DIR)})
    print("DESCRIPTIVE_ONLY")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("plan")
    sub.add_parser("freeze")
    r = sub.add_parser("run")
    r.add_argument("--output", type=Path, required=True)
    r.add_argument("--allow-live", action="store_true")
    r.add_argument("--resume", action="store_true")
    s = sub.add_parser("score")
    s.add_argument("report", type=Path)
    s.add_argument("--output", type=Path, required=True)
    s.add_argument("--resume", action="store_true")
    a = sub.add_parser("analyze")
    a.add_argument("scores", type=Path)
    a.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.command == "plan":
        p = protocol()
        rows = schedule(p)
        for item in rows:
            if not (source_artifacts(item) / "tests").is_dir():
                raise ValueError("saved official deliverable missing: " + source_call_id(item))
        print(json.dumps({"calls": len(rows), "tasks": p["tasks"], "arm": ARM, "compared_arms": list(ARMS3),
                          "model": p["model"], "source_dir": str(SOURCE_DIR), "paid_calls_started": 0}, indent=2))
        return 0
    if args.command == "freeze":
        if LOCK.exists():
            raise ValueError("already frozen; create a successor protocol")
        data = {"frozen_utc": engine.utc_now(), "bindings": bindings(), "schedule": schedule()}
        with LOCK.open("x") as handle:
            json.dump(data, handle, indent=2)
            handle.write("\n")
        return 0
    return {"run": run, "score": score, "analyze": analyze}[args.command](args)


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (ValueError, KeyError, FileNotFoundError) as error:
        print(f"refused: {error}", file=sys.stderr)
        raise SystemExit(3)
